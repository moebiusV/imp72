#!/usr/bin/env python3
"""runoff2md.py IMP.RNO > imp72.md: the DECUS RUNOFF source of the IMP72 manual as Markdown.

The source is typed in capitals and RUNOFF lowers them: a `^` raises the next letter, `^^` ... `\\` raises
everything between, `^&` ... `\\&` underlines, `_` quotes the next character (so `__` is `_` and `_#` is `#`).
Handled commands: .SUBTITLE (a heading), .PARAGRAPH, .SKIP, .BREAK, .INDENT, .LEFT MARGIN, .NOFILL/.FILL (a
code block), .CENTER (the line after it).  .INDEX, .PAGE, .TEST, .RIGHT MARGIN, .TAB STOPS, .SPACING,
.NUMBER, .JUSTIFY and .TITLE only affect the paper and are dropped."""
import re
import sys


def case(text):
    """Apply RUNOFF's capitalization and quoting to one piece of text."""
    out = []
    i = 0
    n = len(text)
    caps = False                  # inside ^^ ... \\
    under = False
    while i < n:
        c = text[i]
        if c == "^" and i + 1 < n:
            d = text[i + 1]
            if d == "^":
                caps = True
                i += 2
                continue
            if d == "&":
                if not under:
                    out.append("_")
                under = True
                i += 2
                continue
            out.append(d.upper() if d.isalpha() else d)
            i += 2
            continue
        if c == "\\":
            if text[i + 1:i + 2] == "\\":          # end of ^^
                caps = False
                i += 2
                continue
            if text[i + 1:i + 2] == "&":          # end of underlining
                if under:
                    out.append("_")
                under = False
                i += 2
                continue
            i += 1                                  # a lone backslash lowers the next letter
            if i < n:
                out.append(text[i].lower())
                i += 1
            continue
        if c == "_" and i + 1 < n:
            out.append(text[i + 1])
            i += 2
            continue
        out.append(c.upper() if (caps and c.isalpha()) else c.lower())
        i += 1
    return "".join(out)


def main(path):
    lines = open(path, encoding="latin-1").read().split("\n")
    md = []
    para = []
    nofill = False
    center = False
    indent = False

    def flush():
        nonlocal para, indent
        if para:
            text = " ".join(x.strip() for x in para if x.strip())
            text = re.sub(r" {2,}", " ", text)
            if text:
                md.append(("- " if indent else "") + text)
                md.append("")
        para = []
        indent = False

    for raw in lines:
        if raw.startswith("."):
            m = re.match(r"\.([A-Za-z]+)\s*(.*)", raw)
            if not m:
                continue
            cmd, arg = m.group(1).upper(), m.group(2)
            if cmd in ("SUBTITLE",):
                flush()
                title = case(arg).strip()
                num = re.match(r"([0-9.]+):", title)
                depth = title.split(":")[0].count(".") + 2 if num else 2
                md.append("#" * min(depth, 6) + " " + title)
                md.append("")
            elif cmd in ("PARAGRAPH", "SKIP", "BREAK", "PAGE"):
                flush()
            elif cmd == "INDENT":
                flush()
                indent = True
            elif cmd == "CENTER":
                flush()
                center = True
            elif cmd == "NOFILL":
                flush()
                nofill = True
                md.append("```")
            elif cmd == "FILL":
                if nofill:
                    while md and md[-1] == "":
                        md.pop()
                    md.append("```")
                    md.append("")
                nofill = False
            continue
        if nofill:
            md.append(case(raw).rstrip())
            continue
        if center:
            center = False
            t = case(raw).strip()
            if t and not re.match(r"^_?[0-9][0-9.]*:", t) and not t.startswith("_"):
                flush()
                md.append("**" + t + "**")
                md.append("")
            continue
        para.append(case(raw))
    flush()
    out = "\n".join(md)
    out = re.sub(r"\n{3,}", "\n\n", out)
    sys.stdout.write("<!-- Generated by tools/runoff2md.py from decus/imp.rno: do not edit. -->\n\n" + out + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
